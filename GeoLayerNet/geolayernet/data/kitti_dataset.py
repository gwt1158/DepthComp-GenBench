"""KITTI Depth Completion dataset (separate from Nyu500Dataset — never reuse it).

Outdoor protocol, PSD/TIP-2025 style, normalized-by-max_depth so the EXISTING
eval/metric path is reused unchanged:
  * depth is read in metres, then divided by ``max_depth`` (default 80) -> [0,1];
    at eval time ``dataset.depth_unit_scale: 80`` converts the [0,1] metrics back
    to metres (RMSE_m, MAE_m, REL, delta1) with no eval.py change.
  * sparse_depth = Velodyne raw/projected depth (~5%); target_depth = annotated /
    groundtruth (semi-dense). valid_mask = sparse>0; target_mask = (0 < gt <= 80 m).

Cropping (PSD-style — NOT the NYU 320x240 resize + 304x228 crop):
  * eval (val/test): bottom-center crop to ``kitti_crop`` = [256, 1216] (H, W).
  * train: random crop to ``train_crop`` = [256, 832] from the bottom band, plus
    optional color jitter.
  * ``resize_to`` (default null/None): if set (e.g. [228, 304]) the crop is then
    resized to that H x W to exactly match the current model input size. Off by
    default => native KITTI 1216x256 / 832x256 is kept (the model is fully-conv).

Output batch keys (identical to Nyu500Dataset): rgb, sparse_depth, target_depth,
valid_mask, target_mask, name.

Format is auto-detected (lockable via ``kitti_layout``):
  * "preprocessed": <root>/<phase>/{rgb|image|image_02, sparse|velodyne_raw,
    gt|groundtruth|target_depth} matched by file stem.
  * "official": KITTI devkit layout — data_depth_velodyne / data_depth_annotated
    (+ raw RGB under raw_root), paired by drive + frame.
  * "manifest": JSONL records generated by tools/prepare_kitti_geolayernet.py
    with paths relative to the official source root.
"""

import json
from pathlib import Path

import numpy as np
import torch
import torchvision.transforms as T
import torchvision.transforms.functional as TF
from PIL import Image

_EXTS = (".png", ".jpg", ".jpeg")
_RGB_DIRS = ("rgb", "image", "image_02", "images", "colored_0", "rgb_image")
_SPARSE_DIRS = ("sparse_depth", "sparse", "velodyne_raw", "velodyne", "lidar")
_GT_DIRS = ("target_depth", "gt", "groundtruth", "annotated", "dense", "depth")


def _list(folder):
    folder = Path(folder)
    if not folder.is_dir():
        return {}
    return {p.stem: p for p in sorted(folder.iterdir()) if p.suffix.lower() in _EXTS}


def _first_existing(base, names, override=None):
    if override:
        names = (override,) + tuple(names)
    for n in names:
        if (Path(base) / n).is_dir():
            return Path(base) / n
    return None


def _read_depth_m(path, png_scale):
    """KITTI uint16 depth PNG -> metres (depth_m = raw / png_scale, default 256)."""
    arr = np.array(Image.open(path))
    if arr.ndim == 3:
        arr = arr[:, :, 0]
    return arr.astype(np.float32) / float(png_scale)


class KittiDataset(torch.utils.data.Dataset):
    def __init__(self, dataroot, phase="test", max_depth=80.0, depth_png_scale=256.0,
                 kitti_layout="auto", rgb_dir=None, sparse_dir=None, gt_dir=None,
                 velodyne_root=None, annotated_root=None, raw_root=None, cam="image_02",
                 kitti_crop=(256, 1216), train_crop=(256, 832), resize_to=None,
                 color_jitter=True, source_root=None, manifest_list=None,
                 config_hint=None, **_ignored):
        self.dataroot = dataroot
        self.phase = phase
        self.max_depth = float(max_depth)
        self.png_scale = float(depth_png_scale)
        self.kitti_crop = tuple(kitti_crop)        # (H, W) bottom-center crop for eval
        self.train_crop = tuple(train_crop)        # (H, W) random crop for train
        self.resize_to = tuple(resize_to) if resize_to else None
        self.color_jitter = bool(color_jitter)
        self.cam = cam
        self.config_hint = config_hint
        self._jitter = T.ColorJitter(0.2, 0.2, 0.2, 0.05)
        self.source_root = Path(source_root) if source_root else Path(dataroot)
        self.manifest_list = manifest_list
        if kitti_layout == "manifest" and not self.manifest_list:
            self.manifest_list = str(Path(dataroot) / "protocol" / f"{phase}.jsonl")

        self.samples = self._index(kitti_layout, rgb_dir, sparse_dir, gt_dir,
                                    velodyne_root, annotated_root, raw_root)
        if not self.samples:
            raise RuntimeError(
                f"[kitti] no samples found for phase '{phase}'.\n"
                f"  dataroot          : {dataroot}\n"
                f"  resolved layout   : {kitti_layout}\n"
                f"  manifest_list     : {manifest_list}\n"
                f"  config            : {config_hint}\n"
                f"  cwd               : {Path.cwd()}\n"
                f"  tried preprocessed dirs under <root>/{phase}/ and the official "
                f"velodyne/annotated/raw layout — set kitti_layout / *_dir / *_root in the config.")
        print(f"[kitti] {phase}: {len(self.samples)} samples (layout auto-resolved)")

    # ------------------------------------------------------------------ #
    def _index(self, layout, rgb_dir, sparse_dir, gt_dir, vel_root, ann_root, raw_root):
        if self.manifest_list:
            return self._index_manifest(self.manifest_list)
        if layout == "manifest":
            if not self.manifest_list:
                raise RuntimeError("[kitti] kitti_layout=manifest requires manifest_list")
            return self._index_manifest(self.manifest_list)
        if layout in ("auto", "preprocessed"):
            s = self._index_preprocessed(rgb_dir, sparse_dir, gt_dir)
            if s or layout == "preprocessed":
                return s
        if layout in ("auto", "official"):
            return self._index_official(vel_root, ann_root, raw_root)
        return []

    def _index_manifest(self, manifest_list):
        manifest = Path(manifest_list)
        if not manifest.is_absolute():
            manifest = Path.cwd() / manifest
        if not manifest.is_file():
            raise RuntimeError(f"[kitti] manifest_list not found: {manifest}")
        out = []
        with open(manifest) as fh:
            for line_no, raw in enumerate(fh, start=1):
                line = raw.strip()
                if not line or line.startswith("#"):
                    continue
                rec = json.loads(line)
                missing = [k for k in ("sample_id", "rgb", "sparse_depth", "target_depth") if k not in rec]
                if missing:
                    raise RuntimeError(f"[kitti] manifest {manifest}:{line_no} missing keys {missing}")
                out.append({
                    "name": str(rec["sample_id"]),
                    "rgb": self.source_root / rec["rgb"],
                    "sparse": self.source_root / rec["sparse_depth"],
                    "gt": self.source_root / rec["target_depth"],
                    "date": rec.get("date"),
                    "drive": rec.get("drive"),
                    "camera": rec.get("camera"),
                    "frame": rec.get("frame"),
                })
        return out

    def _index_preprocessed(self, rgb_dir, sparse_dir, gt_dir):
        base = Path(self.dataroot) / self.phase
        if not base.is_dir():
            base = Path(self.dataroot)
        rd = _first_existing(base, _RGB_DIRS, rgb_dir)
        sd = _first_existing(base, _SPARSE_DIRS, sparse_dir)
        gd = _first_existing(base, _GT_DIRS, gt_dir)
        if not (rd and sd and gd):
            return []
        rgb, sp, gt = _list(rd), _list(sd), _list(gd)
        out = []
        for stem, rp in rgb.items():
            if stem in sp and stem in gt:
                out.append({"name": stem, "rgb": rp, "sparse": sp[stem], "gt": gt[stem]})
        return out

    def _index_official(self, vel_root, ann_root, raw_root):
        root = Path(self.dataroot)
        vel_root = Path(vel_root) if vel_root else root / "data_depth_velodyne"
        ann_root = Path(ann_root) if ann_root else root / "data_depth_annotated"
        raw_root = Path(raw_root) if raw_root else root / "kitti_raw"
        vel_phase = vel_root / self.phase
        if not vel_phase.is_dir():
            return []
        out = []
        for vp in sorted(vel_phase.glob(f"*/proj_depth/velodyne_raw/{self.cam}/*.png")):
            drive = vp.parents[3].name                     # <date>_drive_XXXX_sync
            frame = vp.name
            gt = ann_root / self.phase / drive / "proj_depth" / "groundtruth" / self.cam / frame
            date = drive[:10]
            rgb = raw_root / date / drive / self.cam / "data" / frame
            if gt.is_file() and rgb.is_file():
                out.append({"name": f"{drive}_{vp.stem}", "rgb": rgb, "sparse": vp, "gt": gt})
        return out

    # ------------------------------------------------------------------ #
    def __len__(self):
        return len(self.samples)

    def _crop_box(self, h, w):
        ch, cw = (self.train_crop if self.phase == "train" else self.kitti_crop)
        ch, cw = min(ch, h), min(cw, w)
        top = h - ch                                       # bottom band (sky on top has no GT)
        if self.phase == "train":
            top = np.random.randint(max(h - self.kitti_crop[0], 0), h - ch + 1) if h - ch > 0 else 0
            left = np.random.randint(0, w - cw + 1) if w - cw > 0 else 0
        else:
            left = (w - cw) // 2                            # horizontal center
        return top, left, ch, cw

    def __getitem__(self, i):
        s = self.samples[i]
        rgb = Image.open(s["rgb"]).convert("RGB")
        sparse_m = _read_depth_m(s["sparse"], self.png_scale)
        gt_m = _read_depth_m(s["gt"], self.png_scale)
        rgb_np = np.asarray(rgb)
        h, w = gt_m.shape
        if rgb_np.shape[:2] != (h, w):                     # align rgb to depth grid if needed
            rgb = rgb.resize((w, h), Image.BILINEAR)
            rgb_np = np.asarray(rgb)

        top, left, ch, cw = self._crop_box(h, w)
        rgb_np = np.ascontiguousarray(rgb_np[top:top + ch, left:left + cw, :])
        sparse_m = np.ascontiguousarray(sparse_m[top:top + ch, left:left + cw])
        gt_m = np.ascontiguousarray(gt_m[top:top + ch, left:left + cw])

        rgb = Image.fromarray(rgb_np)
        if self.phase == "train" and self.color_jitter:
            rgb = self._jitter(rgb)
        if self.resize_to is not None:
            rh, rw = self.resize_to
            rgb = rgb.resize((rw, rh), Image.BILINEAR)
            sparse_m = np.asarray(Image.fromarray(sparse_m, mode="F").resize((rw, rh), Image.NEAREST)).copy()
            gt_m = np.asarray(Image.fromarray(gt_m, mode="F").resize((rw, rh), Image.NEAREST)).copy()

        rgb_t = TF.normalize(TF.to_tensor(rgb), (0.5, 0.5, 0.5), (0.5, 0.5, 0.5))   # [-1,1]
        # normalize depth by max_depth -> [0,1]; metrics x depth_unit_scale(=80) -> metres
        sparse = np.clip(sparse_m / self.max_depth, 0.0, 1.0)
        gt = np.clip(gt_m / self.max_depth, 0.0, 1.0)
        sparse_t = torch.from_numpy(sparse).unsqueeze(0).float()
        gt_t = torch.from_numpy(gt).unsqueeze(0).float()
        valid = (torch.from_numpy(sparse_m).unsqueeze(0) > 0).float()
        target_mask = ((torch.from_numpy(gt_m).unsqueeze(0) > 0) &
                       (torch.from_numpy(gt_m).unsqueeze(0) <= self.max_depth)).float()
        return {"rgb": rgb_t, "sparse_depth": sparse_t, "target_depth": gt_t,
                "valid_mask": valid, "target_mask": target_mask, "name": s["name"]}
